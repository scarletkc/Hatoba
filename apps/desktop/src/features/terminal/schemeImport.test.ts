import { describe, expect, it } from "vitest";
import { parseSchemeFile, SchemeImportError, stripJsonComments } from "./schemeImport";
import { paletteOf, schemeFor } from "./schemes";

const HEX = /^#[0-9a-f]{6}$/;

/** Campbell, Windows Terminal's default scheme, as its settings.json lists it. */
const CAMPBELL = {
  name: "Campbell",
  foreground: "#CCCCCC",
  background: "#0C0C0C",
  cursorColor: "#FFFFFF",
  selectionBackground: "#FFFFFF",
  black: "#0C0C0C",
  red: "#C50F1F",
  green: "#13A10E",
  yellow: "#C19C00",
  blue: "#0037DA",
  purple: "#881798",
  cyan: "#3A96DD",
  white: "#CCCCCC",
  brightBlack: "#767676",
  brightRed: "#E74856",
  brightGreen: "#16C60C",
  brightYellow: "#F9F1A5",
  brightBlue: "#3B78FF",
  brightPurple: "#B4009E",
  brightCyan: "#61D6D6",
  brightWhite: "#F2F2F2",
};

function failure(run: () => unknown): string {
  try {
    run();
  } catch (e) {
    if (e instanceof SchemeImportError) return e.reason;
    throw e;
  }
  throw new Error("parsed");
}

describe("Windows Terminal schemes", () => {
  it("read one scheme, with purple as magenta and every colour in lowercase", () => {
    const [scheme] = parseSchemeFile(JSON.stringify(CAMPBELL), "campbell.json");
    expect(scheme.name).toBe("Campbell");
    expect(scheme.mode).toBe("dark");
    expect(scheme.colors.magenta).toBe("#881798");
    expect(scheme.colors.bright_magenta).toBe("#b4009e");
    expect(scheme.colors.cursor).toBe("#ffffff");
    expect(scheme.colors.selection).toBe("#ffffff");
    for (const value of Object.values(scheme.colors)) expect(value).toMatch(HEX);
  });

  it("read every scheme of a settings.json, with its comments and trailing commas", () => {
    const settings = `// This file was initially generated by Windows Terminal
{
    "$schema": "https://aka.ms/terminal-profiles-schema",
    "profiles": { "list": [ { "name": "PowerShell", "commandline": "pwsh.exe", }, ], },
    /* Schemes */
    "schemes": [
        ${JSON.stringify(CAMPBELL)}, // the default
        { "name": "One Half Light", "background": "#FAFAFA", "foreground": "#383A42", "black": "#383A42", "red": "#E45649",
          "green": "#50A14F", "yellow": "#C18301", "blue": "#0184BC", "purple": "#A626A4", "cyan": "#0997B3", "white": "#FAFAFA", },
        { "name": "Not a scheme" },
    ],
}`;
    const schemes = parseSchemeFile(settings, "settings.json");
    expect(schemes.map((s) => [s.name, s.mode])).toEqual([
      ["Campbell", "dark"],
      ["One Half Light", "light"],
    ]);
    // What the file leaves out: the cursor follows the text, the selection blends it into the background, and
    // the bright colours come from Hatoba's scheme for the mode.
    const light = schemes[1].colors;
    expect(light.cursor).toBe("#383a42");
    expect(light.selection).toBe("#c0c0c3");
    expect(light.bright_red).toBe(paletteOf(schemeFor("light", null)).bright_red);
  });

  it("are named after the file when they have no name", () => {
    const { name, ...unnamed } = CAMPBELL;
    expect(name).toBe("Campbell");
    expect(parseSchemeFile(JSON.stringify([unnamed]), "C:\\Users\\kc\\Downloads\\My Theme.json")[0].name).toBe("My Theme");
  });

  it("refuse what is not JSON or holds no scheme", () => {
    expect(failure(() => parseSchemeFile("{ nope", "x.json"))).toBe("unreadable");
    expect(failure(() => parseSchemeFile('{"profiles": {}}', "x.json"))).toBe("noScheme");
    expect(failure(() => parseSchemeFile('{"background": "#000000", "foreground": "#ffffff"}', "x.json"))).toBe("noScheme");
    expect(failure(() => parseSchemeFile('{"background": "black", "foreground": "white", "red": "red"}', "x.json"))).toBe("noScheme");
  });

  it("strip comments but not text inside strings", () => {
    expect(JSON.parse(stripJsonComments('{"url": "https://example.com/*x*/", "a": [1, 2, ], // c\n}'))).toEqual({
      url: "https://example.com/*x*/",
      a: [1, 2],
    });
    expect(JSON.parse(stripJsonComments('{"q": "say \\"hi\\" // not a comment",}'))).toEqual({ q: 'say "hi" // not a comment' });
  });
});

function itermColor(r: number, g: number, b: number, extra = ""): string {
  return `<dict>
    <key>Alpha Component</key><real>1</real>
    <key>Blue Component</key><real>${b}</real>
    <key>Color Space</key><string>sRGB</string>
    <key>Green Component</key><real>${g}</real>
    <key>Red Component</key><real>${r}</real>${extra}
  </dict>`;
}

function itermFile(entries: Record<string, string>): string {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
${Object.entries(entries)
  .map(([key, value]) => `  <key>${key}</key>\n  ${value}`)
  .join("\n")}
</dict>
</plist>`;
}

describe("iTerm2 colour presets", () => {
  const ansi = (suffix = "") =>
    Object.fromEntries(Array.from({ length: 16 }, (_, n) => [`Ansi ${n} Color${suffix}`, itermColor(n / 15, 0.5, 1 - n / 15)]));

  it("read the colours as sRGB, named after the file", () => {
    const text = itermFile({
      ...ansi(),
      "Background Color": itermColor(0.156863, 0.164706, 0.211765),
      "Foreground Color": itermColor(0.972549, 0.972549, 0.94902),
      "Cursor Color": itermColor(1, 1, 1),
      "Selection Color": itermColor(0.266667, 0.278431, 0.352941),
      "Bold Color": itermColor(1, 1, 1),
    });
    const [scheme] = parseSchemeFile(text, "Dracula.itermcolors");
    expect(scheme).toMatchObject({ name: "Dracula", mode: "dark" });
    expect(scheme.colors.background).toBe("#282a36");
    expect(scheme.colors.foreground).toBe("#f8f8f2");
    expect(scheme.colors.selection).toBe("#44475a");
    expect(scheme.colors.black).toBe("#0080ff");
    expect(scheme.colors.bright_white).toBe("#ff8000");
  });

  it("read separate light and dark colours as two schemes", () => {
    const text = itermFile({
      ...ansi(" (Dark)"),
      ...ansi(" (Light)"),
      "Background Color (Dark)": itermColor(0, 0, 0),
      "Foreground Color (Dark)": itermColor(1, 1, 1),
      "Background Color (Light)": itermColor(1, 1, 1),
      "Foreground Color (Light)": itermColor(0, 0, 0),
    });
    const schemes = parseSchemeFile(text, "Builtin.itermcolors");
    expect(schemes.map((s) => [s.name, s.mode])).toEqual([
      ["Builtin (Dark)", "dark"],
      ["Builtin (Light)", "light"],
    ]);
  });

  it("refuse a file that is not a property list or holds no scheme", () => {
    expect(failure(() => parseSchemeFile("<plist><dict><key>x</dict></plist>", "x.itermcolors"))).toBe("unreadable");
    expect(failure(() => parseSchemeFile("<html><body>hi</body></html>", "x.itermcolors"))).toBe("unreadable");
    expect(failure(() => parseSchemeFile(itermFile({ "Background Color": itermColor(0, 0, 0) }), "x.itermcolors"))).toBe("noScheme");
  });
});
